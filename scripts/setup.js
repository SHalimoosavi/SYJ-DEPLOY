#!/usr/bin/env node
/**
 * SYJ Deploy — First-time Setup
 * Run: node scripts/setup.js
 */

const fs = require('fs');
const path = require('path');
const readline = require('readline');
const crypto = require('crypto');

const ENV_PATH = path.join(__dirname, '../.env');

function prompt(rl, question) {
  return new Promise(resolve => rl.question(question, resolve));
}

async function setup() {
  console.log(`
╔══════════════════════════════════════════╗
║        SYJ Deploy — First Setup          ║
║   SAYANJALI NEXUS PRIVATE LIMITED        ║
╚══════════════════════════════════════════╝
`);

  if (fs.existsSync(ENV_PATH)) {
    console.log('✓ .env file already exists. Delete it to re-run setup.\n');
    process.exit(0);
  }

  const rl = readline.createInterface({ input: process.stdin, output: process.stdout });

  const port = await prompt(rl, 'Port [3000]: ') || '3000';
  const adminUser = await prompt(rl, 'Admin username [admin]: ') || 'admin';
  const adminPass = await prompt(rl, 'Admin password [admin123]: ') || 'admin123';

  rl.close();

  const secret = crypto.randomBytes(32).toString('hex');

  const env = `# SYJ Deploy Configuration
# Generated by setup.js — SAYANJALI NEXUS PRIVATE LIMITED

PORT=${port}
SESSION_SECRET=${secret}
ADMIN_USER=${adminUser}
ADMIN_PASSWORD=${adminPass}
NODE_ENV=production
`;

  fs.writeFileSync(ENV_PATH, env);

  console.log(`
✅ Setup complete!

   Dashboard → http://localhost:${port}
   Username  → ${adminUser}
   Password  → ${adminPass}

Run: npm start
`);
}

setup().catch(err => {
  console.error('Setup failed:', err.message);
  process.exit(1);
});
